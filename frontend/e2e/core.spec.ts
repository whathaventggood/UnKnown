import {test,expect} from '@playwright/test'

test('匿名档案的真实探索、持久化、模式、地图与隐私闭环',async({page})=>{
 const errors:string[]=[]
 page.on('pageerror',e=>errors.push(e.message))
 const failedRequests:string[]=[]
 page.on('response',res=>{if(res.url().includes('/api/')&&res.status()>=400)failedRequests.push(`${res.status()} ${new URL(res.url()).pathname}`)})
 await page.goto('/')
 await expect(page.getByRole('dialog')).toBeVisible()
 await page.getByRole('button',{name:'跳过，直接探索'}).click()
 await expect(page.getByRole('dialog')).toHaveCount(0)
 await expect(page.locator('.topic-card')).toHaveCount(5)
 const firstBatch=await page.request.get('/api/discover/today?mode=unknown').then(r=>r.json())
 await page.reload()
 await expect(page.locator('.topic-card')).toHaveCount(5)
 const secondBatch=await page.request.get('/api/discover/today?mode=unknown').then(r=>r.json())
 expect(secondBatch.id).toBe(firstBatch.id)
 await page.screenshot({path:'test-results/discover-desktop.png',fullPage:true})
 const first=page.locator('.topic-card').first()
 const title=await first.locator('.topic-title h2').innerText()
 await first.getByRole('link',{name:'开始探索'}).click()
 await expect(page.locator('.topic-header h1')).toContainText(title)
 await expect(page.locator('.source-list article')).not.toHaveCount(0)
 await expect(page.locator('.ai-offline')).toBeVisible()
 await page.getByRole('button',{name:'收藏这个主题',exact:true}).click()
 await expect(page.getByRole('button',{name:'已收藏 · 点击取消',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'完全陌生',exact:true}).click()
 await expect(page.getByRole('button',{name:'完全陌生',exact:true})).toHaveAttribute('aria-pressed','true')
 await page.getByLabel('现在的学习状态').selectOption('understood')
 await expect(page.getByLabel('现在的学习状态')).toHaveValue('understood')
 const topicUrl=page.url()
 await page.reload()
 await expect(page.getByLabel('现在的学习状态')).toHaveValue('understood')
 await expect(page.getByRole('button',{name:'已收藏 · 点击取消',exact:true})).toBeVisible()
 await page.screenshot({path:'test-results/topic-desktop.png',fullPage:true})
 await page.getByRole('link',{name:'我的探索',exact:true}).first().click()
 await expect(page.locator('.stats-overview')).toContainText('已探索主题')
 await expect(page.locator('.timeline-item').first()).toContainText(title)
 await page.getByRole('button',{name:/我的收藏/}).click()
 await expect(page.locator('.bookmark-item')).toContainText(title)
 await page.getByRole('link',{name:'认知地图',exact:true}).first().click()
 await expect(page.locator('.map-canvas canvas')).toBeVisible()
 await expect(page.locator('.map-bottom')).toContainText(/[1-9]\d* 个节点/)
 await page.screenshot({path:'test-results/map-graph-desktop.png',fullPage:true})
 await page.getByRole('button',{name:'列表视图',exact:true}).click()
 await expect(page.locator('.map-list-item')).not.toHaveCount(0)
 await page.getByLabel('搜索主题或领域').fill(title)
 await expect(page.locator('.map-list-item').filter({hasText:title})).toBeVisible()
 await page.locator('.map-list-item').filter({hasText:title}).focus()
 await page.keyboard.press('Enter')
 await expect(page.locator('.map-inspector')).toContainText('已探索')
 await expect(page.locator('.map-inspector')).toContainText('已收藏')
 await page.screenshot({path:'test-results/map-desktop.png',fullPage:true})
 await page.goto('/')
 await page.getByRole('button',{name:'跨领域桥梁',exact:true}).click()
 await expect(page.locator('.topic-card')).toHaveCount(5)
 await page.getByRole('button',{name:'广域探索',exact:true}).click()
 await expect(page.locator('.topic-card')).toHaveCount(5)
 await page.getByRole('button',{name:'换一组',exact:true}).click()
 await expect(page.locator('.topic-card')).toHaveCount(5)
 await page.getByRole('link',{name:'设置',exact:true}).click()
 await expect(page.locator('#ai')).toContainText('未配置')
 await page.getByRole('button',{name:'保存偏好',exact:true}).click()
 await expect(page.getByRole('button',{name:'已保存',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'清除记录',exact:true}).click()
 await expect(page.getByRole('dialog')).toContainText('共享知识库与非个性化解释会保留')
 await page.getByRole('button',{name:'保留记录',exact:true}).click()
 await expect(page.getByRole('dialog')).toHaveCount(0)
 await page.goto(topicUrl)
 await expect(page.getByRole('button',{name:'已收藏 · 点击取消',exact:true})).toBeVisible()
 expect(errors).toEqual([])
 expect(failedRequests).toEqual([])
})

test('移动端布局、导航、键盘可访问性与实际地图列表',async({page})=>{
 const errors:string[]=[]
 page.on('pageerror',e=>errors.push(e.message))
 await page.setViewportSize({width:390,height:844})
 await page.goto('/')
 await page.getByRole('button',{name:'跳过，直接探索'}).click()
 await expect(page.locator('.topic-card')).toHaveCount(5)
 await page.screenshot({path:'test-results/discover-mobile.png',fullPage:true})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
 await page.getByRole('button',{name:'展开导航',exact:true}).click()
 await page.locator('.mobile-nav').getByRole('link',{name:'认知地图',exact:true}).click()
 await expect(page.locator('.map-list')).toBeVisible()
 await expect(page.locator('.map-list-item')).not.toHaveCount(0)
 await page.screenshot({path:'test-results/map-mobile.png',fullPage:true})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
 const mapData=await page.request.get('/api/map?limit=80').then(r=>r.json())
 const mobileTopic=mapData.nodes.find((n:{type:string})=>n.type==='topic')
 await page.getByLabel('搜索主题或领域').fill(mobileTopic.name)
 await page.locator('.map-list-item').filter({hasText:mobileTopic.name}).click()
 await page.getByRole('link',{name:'阅读主题',exact:true}).click()
 await expect(page.locator('.topic-header h1')).toContainText(mobileTopic.name)
 await page.screenshot({path:'test-results/topic-mobile.png',fullPage:true})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
 await page.getByRole('button',{name:'切换深色主题',exact:true}).click()
 await expect(page.locator('html')).toHaveClass(/dark/)
 await page.getByRole('link',{name:'设置',exact:true}).click()
 await page.screenshot({path:'test-results/settings-mobile-dark.png',fullPage:true})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
 await page.getByRole('button',{name:'清除记录',exact:true}).click()
 await page.getByLabel('输入“清除”以确认').fill('清除')
 await page.getByRole('button',{name:'确认清除',exact:true}).click()
 await expect(page.getByRole('dialog')).toContainText('你的已知，是探索的起点。')
 await page.getByRole('button',{name:'跳过，直接探索'}).click()
 const stats=await page.request.get('/api/stats').then(r=>r.json())
 expect(stats.explored_count).toBe(0)
 expect(stats.bookmark_count).toBe(0)
 expect(errors).toEqual([])
})
